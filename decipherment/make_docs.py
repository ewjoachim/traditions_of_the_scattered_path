def row(word):
    meaning, confidence = LEX[word]
    count = str(COUNT[word])
    if COUNT[word] == 0:
        forms = sorted(form for form in COUNT if split_suffix(form)[0] == word)
        shown = ", ".join(f"`{form}`" for form in forms)
        count = f"{sum(COUNT[form] for form in forms)} (as {shown})"
    return f"| `{word}` | {meaning.replace('|', ' / ')} | {count} | {confidence} |"


def table(words):
    lines = ["| Word | Meaning | Count | Confidence |", "|---|---|---|---|"]
    lines += [row(word) for word in words]
    return "\n".join(lines)


def build_glossary():
    total = sum(COUNT.values())
    known = sum(count for word, count in COUNT.items() if lookup(word))
    by_confidence = collections.Counter(confidence for _, confidence in LEX.values())
    grouped = set()
    parts = []
    for title, words in GROUPS:
        words = [word for word in words.split() if word in LEX]
        grouped.update(words)
        parts.append(f"#### {title}\n\n{table(words)}")
    names = "\n".join(f"| `{word}` | {description} | {COUNT[word]} |" for word, description in NAMES.items())
    rest = [word for word in LEX if word not in grouped and word not in NAMES and not LEX[word][0].isupper()]
    solid = sorted((word for word in rest if LEX[word][1] in "AB"), key=lambda word: (-COUNT[word], word))
    guess = sorted((word for word in rest if LEX[word][1] == "C"), key=lambda word: (-COUNT[word], word))
    values = {
        "TOTAL": f"{total:,}",
        "KNOWN": f"{known:,}",
        "PCT": str(round(100 * known / total)),
        "N_A": str(by_confidence["A"]),
        "N_B": str(by_confidence["B"]),
        "N_C": str(by_confidence["C"]),
        "GRAMMAR": "\n\n".join(parts),
        "NAMES": names,
        "SOLID": table(solid),
        "GUESS": table(guess),
    }
    text = (HERE / "glossary_template.md").read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    if "{{" in text:
        raise ValueError(f"glossary_template.md: unknown placeholder {text[text.index('{{'):][:40]}")
    (REPO / "glossary.md").write_text(GENERATED + text, encoding="utf-8")
    print(f"glossary.md: {len(LEX)} entries; {known} of {total} words glossed")


def build_translation():
    rows = read_tsv("translations.tsv", ["section", "sentence", "english"])
    drafts = {(int(section), int(sentence)): english for section, sentence, english in rows}
    expected = {(i, j) for i, j, _ in SENTS}
    if len(drafts) != len(rows) or set(drafts) != expected:
        raise ValueError(
            "translations.tsv: needs exactly one row per sentence; "
            f"missing {sorted(expected - set(drafts))}, unexpected {sorted(set(drafts) - expected)}, "
            f"{len(rows) - len(drafts)} repeated"
        )
    lines = [(HERE / "translation_header.md").read_text(encoding="utf-8").rstrip(), ""]
    for i, section in enumerate(SECS):
        title, pages, picture = SECTIONS[i]
        lines += [f"## {i}. {title} ({pages})", "", f"Picture: {picture}", ""]
        for j, sentence in enumerate(section):
            lines += [f"**{i}.{j}** *{' '.join(sentence)}.*", "", f"> {drafts[i, j]}", ""]
    (REPO / "translation.md").write_text(GENERATED + "\n".join(lines), encoding="utf-8")
    guesses = sum(english.count("[") for english in drafts.values())
    print(f"translation.md: {len(drafts)} sentences; {guesses} bracketed guesses")


build_glossary()
build_translation()
